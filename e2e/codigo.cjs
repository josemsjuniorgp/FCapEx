const { chromium } = require('playwright');
const S = process.argv[2], SITE = 'http://127.0.0.1:5173';
(async () => {
  const b = await chromium.launch();
  const p = await (await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 })).newPage();
  p.setDefaultTimeout(15000); p.on('pageerror', e => console.log('pageerror', e.message));
  const passo = async (n, fn) => { try { await fn(); console.log('✔', n); } catch (e) { console.log('✘', n, '-', e.message.split('\n').slice(0, 3).join(' | ')); console.log((await p.locator('body').innerText().catch(() => '')).slice(0, 700)); await p.screenshot({ path: `${S}/shots/erro.png` }); process.exit(1); } };
  await passo('conta, empresa, cliente e projeto', async () => {
    await p.goto(SITE);
    await p.getByRole('button', { name: 'Não tem conta? Criar conta' }).click();
    await p.getByLabel('E-mail').fill(`cod${Date.now()}@teste.dev`); await p.getByLabel('Senha').fill('senha-teste-123');
    await p.getByRole('button', { name: 'Criar conta' }).click();
    await p.getByPlaceholder('Nome da empresa').fill('Empresa Código'); await p.getByRole('button', { name: 'Criar', exact: true }).click();
    await p.getByRole('button', { name: '+ Novo cliente' }).click(); await p.getByPlaceholder('Nome do cliente').fill('Cliente X'); await p.getByRole('button', { name: 'Criar cliente' }).click();
    await p.getByRole('button', { name: 'Novo projeto' }).click();
    await p.getByPlaceholder('Nome do projeto').fill('Projeto 1000'); await p.getByRole('button', { name: 'Criar projeto' }).click();
    await p.getByRole('heading', { name: 'Projeto 1000' }).waitFor();
  });
  await passo('Nova PX: código digitado livremente', async () => {
    await p.getByRole('button', { name: 'Novo Mapa de Preços' }).click();
    await p.getByPlaceholder('Ex.: Estimativa classe 3').fill('Estimativa A1');
    if (!(await p.getByRole('button', { name: 'Criar Mapa' }).isDisabled())) throw new Error('deveria exigir o código');
    await p.getByText('Mapa Padrão', { exact: true }).waitFor();
    await p.getByText('Você pode inserir ou excluir colunas').first().waitFor();
    if (await p.getByText('PX Simplificada').count()) throw new Error('PX Simplificada ainda aparece');
    if (await p.getByText('PX Padrão v1').count()) throw new Error('ainda aparece v1');
    await p.getByPlaceholder('Ex.: A1-1000-G-PB-0001').fill('PX-A1-1000-G-PB-0001');
    await p.screenshot({ path: `${S}/shots/10-nova-px-codigo.png` });
    await p.getByRole('button', { name: 'Criar Mapa' }).click();
    await p.locator('.px-cab', { hasText: 'PX-A1-1000-G-PB-0001' }).filter({ hasText: 'Rev 0' }).waitFor();
  });
  await passo('código em formato livre e bloqueio de código repetido', async () => {
    await p.getByRole('button', { name: 'Voltar para Projetos' }).click();
    await p.getByRole('button', { name: 'Novo Mapa de Preços' }).click();
    await p.getByPlaceholder('Ex.: A1-1000-G-PB-0001').fill('ORÇ 2026/15');
    await p.getByPlaceholder('Ex.: Estimativa classe 3').fill('Formato livre');
    await p.getByRole('button', { name: 'Criar Mapa' }).click();
    await p.locator('.px-cab', { hasText: 'ORÇ 2026/15' }).filter({ hasText: 'Rev 0' }).waitFor();
    await p.getByRole('button', { name: 'Voltar para Projetos' }).click();
    await p.getByRole('button', { name: 'Novo Mapa de Preços' }).click();
    await p.getByPlaceholder('Ex.: A1-1000-G-PB-0001').fill('ORÇ 2026/15');
    await p.getByPlaceholder('Ex.: Estimativa classe 3').fill('Repetida');
    await p.getByRole('button', { name: 'Criar Mapa' }).click();
    await p.getByText(/Já existe um Mapa com o código ORÇ 2026\/15/).waitFor();
    await p.getByRole('button', { name: 'Cancelar' }).click();
  });
  await passo('Parâmetros não tem mais a seção de padrão', async () => {
    await p.getByRole('link', { name: 'Parâmetros' }).click();
    await p.getByRole('heading', { name: 'Moedas e câmbio' }).waitFor();
    if (await p.getByRole('heading', { name: 'Código da PX' }).count()) throw new Error('seção ainda aparece');
    await p.getByRole('link', { name: 'Projetos' }).click();
  });
  await passo('marcar item como título e voltar, sem perder valores', async () => {
    await p.locator('.px-card', { hasText: 'PX-A1-1000-G-PB-0001' }).getByRole('button', { name: 'Editar', exact: true }).click();
    await p.locator('.px-cab', { hasText: 'PX-A1-1000-G-PB-0001' }).filter({ hasText: 'Rev 0' }).waitFor();
    await p.getByRole('button', { name: 'Inserir item' }).click();
    const l = p.locator('table.grid tbody tr').first();
    const desc = l.locator('td.in-c :is(input,textarea)').nth(5);
    await l.locator('td.in-c :is(input,textarea)').nth(1).fill('9.9'); await l.locator('td.in-c :is(input,textarea)').nth(1).press('Enter');
    await desc.fill('OBRAS CIVIS'); await desc.press('Enter');
    const qtd = l.locator('td.in-c input.numi').first(); await qtd.fill('5'); await qtd.press('Enter');
    await p.waitForTimeout(500);
    await l.getByRole('button', { name: 'Virar título' }).click();
    await l.getByText('Título', { exact: true }).waitFor().catch(() => {});
    if (await l.locator('input.numi').count()) throw new Error('título ainda tem campo de quantidade');
    if (!(await l.getAttribute('class')).includes('title nv1')) throw new Error('linha não virou título de 1º nível: ' + await l.getAttribute('class'));
    await p.reload();
    await p.locator('table.grid tbody tr').first().getByRole('button', { name: 'Virar item' }).click();
    await p.waitForTimeout(500);
    const v = await p.locator('table.grid tbody tr').first().locator('input.numi').first().inputValue();
    if (v !== '5,00') throw new Error('quantidade não voltou: ' + v);
  });
  await passo('excluir e inserir coluna da PX sem perder valores', async () => {
    const hh = () => p.locator('table.grid thead tr.h th', { hasText: /^HH$/ });
    const l = p.locator('table.grid tbody tr').first();
    const idx = await p.locator('table.grid thead tr.h th').evaluateAll(ths => ths.findIndex(t => t.textContent === 'HH'));
    const celHH = l.locator('td').nth(idx).locator('input, textarea');
    await celHH.fill('120'); await celHH.press('Enter'); await p.waitForTimeout(500);
    await p.getByRole('button', { name: 'Gerenciar colunas' }).click();
    await p.locator('.side-panel').getByLabel('HH').first().uncheck();
    await p.getByText('Coluna excluída.').waitFor();
    if (await hh().count()) throw new Error('HH ainda aparece');
    await p.reload();
    if (await hh().count()) throw new Error('HH voltou depois de recarregar');
    await p.getByRole('button', { name: 'Gerenciar colunas' }).click();
    await p.locator('.side-panel').getByLabel('HH').first().check();
    await p.getByText('Coluna inserida.').waitFor();
    await hh().waitFor();
    const v = await p.locator('table.grid tbody tr').first().locator('td').nth(idx).locator('input, textarea').inputValue();
    if (v !== '120') throw new Error('valor de HH não voltou: ' + v);
    await p.screenshot({ path: `${S}/shots/11-colunas.png` });
    await p.getByRole('button', { name: 'Fechar' }).click();
  });
  await passo('importar modelo: sem caixas de seleção, colunas vêm do Excel', async () => {
    await p.getByRole('button', { name: 'Voltar para Projetos' }).click();
    await p.getByRole('button', { name: 'Novo Mapa de Preços' }).click();
    await p.getByPlaceholder('Ex.: A1-1000-G-PB-0001').fill('PX-MODELO-01');
    await p.getByPlaceholder('Ex.: Estimativa classe 3').fill('Pelo modelo do cliente');
    await p.getByText('Importar modelo').click();
    if (await p.locator('.colpick').count()) throw new Error('caixas de seleção aparecem antes do arquivo');
    await p.locator('input[type=file]').setInputFiles(`${S}/Modelo-Cliente.xlsx`);
    await p.getByText(/Colunas que o Mapa vai ter \(\d+\)/).waitFor();
    if (await p.locator('.colpick').count()) throw new Error('caixas de seleção aparecem depois do arquivo');
    const lista = await p.locator('.group-box', { hasText: 'Colunas que o Mapa vai ter' }).innerText();
    for (const c of ['Item PQ', 'Descrição', 'Unid', 'Quantidade', 'Moeda', 'Preço unit.', 'Total geral', 'Check'])
      if (!lista.includes(c)) throw new Error('faltou ' + c + ' em: ' + lista);
    if (lista.includes('HH') || lista.includes('Pacote')) throw new Error('coluna que não está no Excel: ' + lista);
    await p.screenshot({ path: `${S}/shots/12-importar-modelo.png` });
    await p.getByRole('button', { name: 'Criar Mapa' }).click();
    await p.locator('.px-cab', { hasText: 'PX-MODELO-01' }).filter({ hasText: 'Rev 0' }).waitFor();
    const cab = await p.locator('table.grid thead tr.h th').allInnerTexts();
    if (cab.some(h => /^(HH|Pacote|BDI)$/.test(h.trim()))) throw new Error('grade com colunas a mais: ' + cab.join('|'));
    if (!cab.some(h => h.trim() === 'Moeda')) throw new Error('grade sem Moeda: ' + cab.join('|'));
    await p.getByRole('button', { name: 'Voltar para Projetos' }).click();
    await p.getByRole('button', { name: 'Editar', exact: true }).first().click();
  });
  await passo('corrigir código e nome pelo lápis do cabeçalho', async () => {
    await p.getByRole('button', { name: 'Corrigir código e nome' }).click();
    const cab = p.locator('.px-cab');
    await cab.getByLabel('Código do Mapa').fill('PX-CORRIGIDA-01');
    await cab.getByLabel('Nome do Mapa').fill('Nome corrigido');
    await cab.getByRole('button', { name: 'Salvar' }).click();
    await p.getByText('Código e nome salvos.').waitFor();
    await cab.getByRole('heading', { name: 'Nome corrigido' }).waitFor();
    await cab.getByText('PX-CORRIGIDA-01').waitFor();
    await p.screenshot({ path: `${S}/shots/16-corrigir.png` });
  });
  await passo('código repetido é recusado ao corrigir', async () => {
    await p.getByRole('button', { name: 'Corrigir código e nome' }).click();
    const cab = p.locator('.px-cab');
    await cab.getByLabel('Código do Mapa').fill('PX-MODELO-01');
    await cab.getByRole('button', { name: 'Salvar' }).click();
    await p.getByText('Já existe um Mapa com esse código.').waitFor();
    await cab.getByRole('button', { name: 'Cancelar' }).click();
    await cab.getByText('PX-CORRIGIDA-01').waitFor();
  });
  await passo('corrigir pelo "Renomear" do cartão na tela Projetos', async () => {
    await p.getByRole('button', { name: 'Voltar para Projetos' }).click();
    const card = p.locator('.px-card', { hasText: 'PX-CORRIGIDA-01' });
    await card.getByRole('button', { name: 'Renomear' }).click();
    const aberto = p.locator('.px-card', { has: p.locator('.renomear') });
    if ((await aberto.getByLabel('Código do Mapa').inputValue()) !== 'PX-CORRIGIDA-01') throw new Error('código não veio preenchido');
    await aberto.getByLabel('Nome do Mapa').fill('Nome pelo cartão');
    await aberto.getByRole('button', { name: 'Salvar' }).click();
    await p.locator('.px-card', { hasText: 'Nome pelo cartão' }).waitFor();
    await p.locator('.px-card', { hasText: 'Nome pelo cartão' }).getByRole('button', { name: 'Editar', exact: true }).click();
  });
  await passo('editar o código em Dados da PX', async () => {
    await p.getByRole('button', { name: 'Dados do Mapa' }).click();
    await p.getByRole('textbox', { name: 'Código' }).fill('PX-A1-1000-G-PB-0001-B');
    await p.getByRole('button', { name: 'Salvar', exact: true }).click();
    await p.locator('.px-cab', { hasText: 'PX-A1-1000-G-PB-0001-B' }).filter({ hasText: 'Rev 0' }).waitFor();
  });
  console.log('FIM'); await b.close();
})();
