const { chromium } = require('playwright');
const S = process.argv[2], SITE = 'http://127.0.0.1:5173';
const num = t => parseFloat(t.replace(/[^\d,-]/g, '').replace(',', '.'));
(async () => {
  const b = await chromium.launch();
  const p = await (await b.newContext({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 2 })).newPage();
  p.setDefaultTimeout(15000); p.on('pageerror', e => console.log('pageerror', e.message));
  const passo = async (n, fn) => { try { await fn(); console.log('✔', n); } catch (e) { console.log('✘', n, '-', e.message.split('\n').slice(0, 3).join(' | ')); console.log((await p.locator('body').innerText().catch(() => '')).slice(0, 600)); await p.screenshot({ path: `${S}/shots/erro.png` }); process.exit(1); } };
  await passo('conta, empresa, cliente, projeto e PX', async () => {
    await p.goto(SITE);
    await p.getByRole('button', { name: 'Não tem conta? Criar conta' }).click();
    await p.getByLabel('E-mail').fill(`trib${Date.now()}@teste.dev`); await p.getByLabel('Senha').fill('senha-teste-123');
    await p.getByRole('button', { name: 'Criar conta' }).click();
    await p.getByPlaceholder('Nome da empresa').fill('Empresa Tributos'); await p.getByRole('button', { name: 'Criar', exact: true }).click();
    await p.getByRole('button', { name: '+ Novo cliente' }).click(); await p.getByPlaceholder('Nome do cliente').fill('Cliente T'); await p.getByRole('button', { name: 'Criar cliente' }).click();
    await p.getByRole('button', { name: 'Novo projeto' }).click(); await p.getByPlaceholder('Nome do projeto').fill('Projeto T'); await p.getByRole('button', { name: 'Criar projeto' }).click();
    await p.getByRole('button', { name: 'Nova PX' }).click();
    await p.getByPlaceholder('Ex.: PX-A1-1000-G-PB-0001').fill('PX-T-01'); await p.getByPlaceholder('Ex.: Estimativa classe 3').fill('Teste tributos');
    await p.getByRole('button', { name: 'Criar PX' }).click(); await p.locator('.px-cab', { hasText: 'PX-T-01' }).waitFor();
  });
  await passo('Parâmetros: 7 tributos padrão e criar CSLL 1% só para serviço', async () => {
    await p.getByRole('link', { name: 'Parâmetros', exact: true }).click();
    await p.getByRole('heading', { name: 'Tributos' }).waitFor();
    for (const t of ['II', 'IPI', 'PIS', 'COFINS', 'ICMS', 'ISS', 'IRRF']) await p.getByRole('cell', { name: t, exact: true }).waitFor();
    if (await p.getByRole('heading', { name: /Pacotes de serviço|Alíquotas por regime/ }).count()) throw new Error('seções antigas ainda aparecem');
    await p.getByPlaceholder('ex.: CSLL').fill('CSLL');
    await p.getByPlaceholder('1,00').fill('1');
    await p.locator('.group-box', { hasText: 'Novo tributo' }).getByLabel('Fornecimento').uncheck();
    await p.getByRole('button', { name: 'Adicionar tributo' }).click();
    await p.getByText('Tributo CSLL criado.').waitFor();
    await p.getByRole('cell', { name: 'CSLL', exact: true }).waitFor();
    await p.screenshot({ path: `${S}/shots/19-tributos-parametros.png`, fullPage: true });
  });
  let colIss, colCsll, colTrib, colGer, linha;
  const td = h => linha.locator('td').nth(h);
  const lerCab = async () => {
    const cab = (await p.locator('table.grid thead tr.h th').allInnerTexts()).map(x => x.replace(/fx$/, '').trim());
    colIss = cab.indexOf('ISS (R$)'); colCsll = cab.indexOf('CSLL (R$)'); colTrib = cab.indexOf('Tributos (R$)'); colGer = cab.indexOf('Total geral (R$)');
    return cab;
  };
  await passo('inserir colunas ISS e CSLL na PX', async () => {
    await p.getByRole('link', { name: 'Projetos', exact: true }).click();
    await p.getByRole('button', { name: 'Editar' }).first().click();
    await p.getByRole('button', { name: 'Colunas' }).click();
    await p.locator('.side-panel').getByLabel('ISS (R$)').first().check(); await p.getByText('Coluna inserida.').waitFor();
    await p.locator('.side-panel').getByLabel('CSLL (R$)').first().check(); await p.waitForTimeout(600);
    await p.getByRole('button', { name: 'Fechar' }).click();
    const cab = await lerCab();
    if (colIss < 0 || colCsll < 0) throw new Error('colunas não apareceram: ' + cab.join('|'));
    if (!(colIss < colCsll && colCsll < colTrib)) throw new Error('ordem errada: ' + cab.join('|'));
  });
  await passo('item de serviço nacional: ISS e CSLL calculados (parcial × alíquota)', async () => {
    await p.getByRole('button', { name: 'Inserir item' }).click();
    const cab = await lerCab();
    linha = p.locator('table.grid tbody tr').first();
    const col = h => cab.indexOf(h);
    const escrever = async (h, v) => { const i = td(col(h)).locator('input, textarea'); await i.fill(v); await i.press('Enter'); await p.waitForTimeout(250); };
    await escrever('Descrição', 'Montagem eletromecânica');
    await escrever('Quantidade', '1');
    await td(col('Tipo de Trabalho')).locator('select').selectOption('M'); await p.waitForTimeout(250);
    await td(col('Natureza')).locator('select').selectOption('N'); await p.waitForTimeout(250);
    await td(col('Moeda')).locator('select').selectOption('BRL'); await p.waitForTimeout(250);
    await escrever('Preço unit.', '1000');
    await linha.getByText('OK', { exact: true }).waitFor();
    const aliq = 0.0165 + 0.076 + 0.05 + 0.01, parc = 1000 / (1 - aliq);
    const iss = num(await td(colIss).locator('span').last().innerText()), csll = num(await td(colCsll).locator('span').last().innerText());
    if (Math.abs(iss - parc * 0.05) > 0.01) throw new Error(`ISS ${iss} ≠ ${(parc * 0.05).toFixed(2)}`);
    if (Math.abs(csll - parc * 0.01) > 0.01) throw new Error(`CSLL ${csll} ≠ ${(parc * 0.01).toFixed(2)}`);
    const ger = num(await td(colGer).innerText());
    if (Math.abs(ger - parc) > 0.01) throw new Error(`total ${ger} ≠ ${parc.toFixed(2)}`);
    if (!(await td(colIss).locator('input[type=checkbox]').isChecked())) throw new Error('ISS deveria começar ligado');
    await p.screenshot({ path: `${S}/shots/20-tributos-grade.png` });
  });
  await passo('desligar ISS na linha: valor "desligado" e total recalculado; fica salvo', async () => {
    await td(colIss).locator('input[type=checkbox]').uncheck(); await p.waitForTimeout(700);
    if ((await td(colIss).locator('span').last().innerText()).trim() !== '0,00') throw new Error('ISS desligado deveria mostrar 0,00: ' + await td(colIss).innerText());
    const parc = 1000 / (1 - (0.0165 + 0.076 + 0.01));
    const ger = num(await td(colGer).innerText());
    if (Math.abs(ger - parc) > 0.01) throw new Error(`total após desligar ${ger} ≠ ${parc.toFixed(2)}`);
    const dica = await linha.locator('td.chk').getAttribute('title');
    if (/ISS/.test(dica)) throw new Error('Check ainda lista ISS: ' + dica);
    await p.reload(); linha = p.locator('table.grid tbody tr').first();
    await linha.getByText('OK', { exact: true }).waitFor(); await lerCab();
    if (colIss < 0) throw new Error('coluna ISS sumiu após recarregar');
    if (await td(colIss).locator('input[type=checkbox]').isChecked()) throw new Error('desligamento não ficou salvo');
    if (!(await td(colIss).locator('.trib-manual').count())) throw new Error('sem marca de escolha manual');
  });
  await passo('ligar ICMS manualmente num serviço (regra não aplicaria)', async () => {
    await p.getByRole('button', { name: 'Colunas' }).click();
    await p.locator('.side-panel').getByLabel('ICMS (R$)').first().check(); await p.waitForTimeout(600);
    await p.getByRole('button', { name: 'Fechar' }).click();
    const cab = await lerCab(); const colIcms = cab.indexOf('ICMS (R$)');
    linha = p.locator('table.grid tbody tr').first();
    if (await td(colIcms).locator('input[type=checkbox]').isChecked()) throw new Error('ICMS não deveria começar ligado em serviço');
    await td(colIcms).locator('input[type=checkbox]').check(); await p.waitForTimeout(600);
    if ((await td(colIcms).locator('span').last().innerText()).trim() !== '0,00') throw new Error('ICMS (0%) ligado deveria mostrar 0,00: ' + await td(colIcms).innerText());
  });
  await p.evaluate(() => { const g = document.querySelector('.gridwrap'); const th = [...document.querySelectorAll('table.grid thead tr.h th')].find(t => t.textContent.startsWith('Preço unit')); g.scrollLeft = th.offsetLeft - 60; });
  await p.waitForTimeout(300);
  await p.locator('.workspace').screenshot({ path: `${S}/shots/21-tributos-colunas.png` });
  console.log('FIM'); await b.close();
})();
